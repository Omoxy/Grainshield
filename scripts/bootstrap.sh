#!/usr/bin/env bash
set -euo pipefail

# GrainShield Local Dev Bootstrap
# Usage: ./scripts/bootstrap.sh
# Generates secrets, creates .env files, validates prerequisites.
# Safe to re-run — skips files that already exist.

ROOT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT_DIR"

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

ok()   { printf "${GREEN}[OK]${NC}   %s\n" "$1"; }
warn() { printf "${YELLOW}[WARN]${NC} %s\n" "$1"; }
fail() { printf "${RED}[FAIL]${NC} %s\n" "$1"; }

errors=0

# ─── Prerequisite checks ─────────────────────────────────────────────────

echo "=== GrainShield Bootstrap ==="
echo ""
echo "Checking prerequisites..."

for cmd in docker go node npm openssl; do
  if command -v "$cmd" &>/dev/null; then
    ver=$("$cmd" --version 2>/dev/null | head -1 || echo "installed")
    ok "$cmd: $ver"
  else
    fail "$cmd not found"
    errors=$((errors + 1))
  fi
done

if command -v docker &>/dev/null; then
  if docker compose version &>/dev/null; then
    ok "docker compose: $(docker compose version --short 2>/dev/null)"
  elif docker-compose version &>/dev/null; then
    ok "docker-compose (legacy): $(docker-compose version --short 2>/dev/null)"
  else
    fail "docker compose plugin not found"
    errors=$((errors + 1))
  fi
fi

if [ "$errors" -gt 0 ]; then
  echo ""
  fail "Missing $errors prerequisite(s). Install them and re-run."
  exit 1
fi

echo ""
echo "Generating secrets..."

# ─── Generate secrets ─────────────────────────────────────────────────────

gen_secret() { openssl rand -base64 "$1" 2>/dev/null | tr -d '\n'; }

JWT_SECRET="${JWT_SECRET:-$(gen_secret 48)}"
POSTGRES_PASSWORD="${POSTGRES_PASSWORD:-$(gen_secret 24)}"
REDIS_PASSWORD="${REDIS_PASSWORD:-$(gen_secret 24)}"
ENCRYPTION_KEY="${ENCRYPTION_KEY:-$(gen_secret 32)}"

# ─── Root .env ────────────────────────────────────────────────────────────

if [ -f "$ROOT_DIR/.env" ]; then
  warn ".env already exists — not overwriting"
else
  cat > "$ROOT_DIR/.env" <<EOF
# Generated by scripts/bootstrap.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# SECURITY: Never commit this file.

POSTGRES_PASSWORD=$POSTGRES_PASSWORD
REDIS_PASSWORD=$REDIS_PASSWORD
JWT_SECRET=$JWT_SECRET
ENCRYPTION_KEY=$ENCRYPTION_KEY
KAFKA_BROKERS=kafka:9092

# Africa's Talking (optional — notification-service starts without these)
# AT_API_KEY=
# AT_USERNAME=
# AT_ENVIRONMENT=sandbox
EOF
  ok "Created .env"
fi

# ─── Frontend .env.local ─────────────────────────────────────────────────

FRONTEND_DIR="$ROOT_DIR/grainshield-app"
if [ -d "$FRONTEND_DIR" ]; then
  if [ -f "$FRONTEND_DIR/.env.local" ]; then
    warn "grainshield-app/.env.local already exists — not overwriting"
  else
    cat > "$FRONTEND_DIR/.env.local" <<EOF
# Generated by scripts/bootstrap.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Must match JWT_SECRET in root .env

JWT_SECRET=$JWT_SECRET

FARMER_SERVICE_URL=http://localhost:8080
POLICY_SERVICE_URL=http://localhost:8081
PAYMENT_SERVICE_URL=http://localhost:8082
PRICE_SERVICE_URL=http://localhost:8083
RISK_SERVICE_URL=http://localhost:8084
WAREHOUSE_SERVICE_URL=http://localhost:8085
NOTIFICATION_SERVICE_URL=http://localhost:8086
EOF
    ok "Created grainshield-app/.env.local"
  fi
else
  warn "grainshield-app/ not found — skipping frontend .env.local"
fi

# ─── Install frontend deps ───────────────────────────────────────────────

if [ -d "$FRONTEND_DIR" ] && [ -f "$FRONTEND_DIR/package.json" ]; then
  if [ ! -d "$FRONTEND_DIR/node_modules" ]; then
    echo ""
    echo "Installing frontend dependencies..."
    (cd "$FRONTEND_DIR" && npm install)
    ok "Frontend dependencies installed"
  else
    ok "Frontend node_modules already present"
  fi
fi

# ─── Summary ──────────────────────────────────────────────────────────────

echo ""
echo "=== Bootstrap Complete ==="
echo ""
echo "Next steps:"
echo "  1. Start infrastructure:  docker compose up -d"
echo "  2. Wait for healthy:      docker compose ps"
echo "  3. Start frontend:        cd grainshield-app && npm run dev"
echo ""
echo "Dev accounts (optional for local testing):"
echo "  Run: bash scripts/dev-seed.sh"
echo ""
echo "Dashboards:"
echo "  Frontend:  http://localhost:3000"
echo "  Kafka UI:  http://localhost:9080"
echo ""
